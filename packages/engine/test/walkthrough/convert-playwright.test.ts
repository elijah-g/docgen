import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import * as YAML from "yaml";
import { convertPlaywrightFile } from "../../src/walkthrough/convert-playwright.js";
import { WalkthroughDocSchema, docToWalkthrough } from "../../src/walkthrough/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const fixture = join(here, "../fixtures/playwright/herd.e2e.ts");
const text = readFileSync(fixture, "utf8");

describe("convertPlaywrightFile", () => {
  it("produces one draft per test(), folding in beforeEach and the describe title", () => {
    const { drafts } = convertPlaywrightFile(text, fixture);
    expect(drafts).toHaveLength(2);

    const [herd, standalone] = drafts;
    expect(herd.id).toBe("ui-herd-list-search-and-filters-examples-10-to-12");
    expect(standalone.id).toBe("ui-standalone-test-with-no-describe");
  });

  it("every draft parses and validates against our own schema, TODOs and all", () => {
    const { drafts } = convertPlaywrightFile(text, fixture);
    for (const draft of drafts) {
      const raw = YAML.parse(draft.yaml);
      const parsed = WalkthroughDocSchema.parse(raw);
      const wt = docToWalkthrough(parsed);
      expect(wt.steps.length).toBeGreaterThan(0);
    }
  });

  it("maps goto, click, fill, select, check and expect toBeVisible/toHaveText/toHaveURL", () => {
    const { drafts } = convertPlaywrightFile(text, fixture);
    const herd = drafts[0];
    const raw = YAML.parse(herd.yaml);
    const actions = raw.steps.flatMap((s: { actions?: unknown[] }) => s.actions ?? []);

    expect(actions).toEqual(
      expect.arrayContaining([
        { do: "goto", path: "/livestock/herd" },
        { do: "waitForUrl", pattern: "q=10" },
      ]),
    );
    expect(actions.some((a: { do: string }) => a.do === "click")).toBe(true);
    expect(actions.some((a: { do: string }) => a.do === "type")).toBe(true);
    expect(actions.some((a: { do: string }) => a.do === "select" && a.option === "Example Mob A")).toBe(true);
  });

  it("folds the within-scoped filter/within chain into a nested target", () => {
    const { drafts } = convertPlaywrightFile(text, fixture);
    const raw = YAML.parse(drafts[0].yaml);
    const actions: Array<{ do: string; target?: { within?: { role?: string; name?: string } } }> =
      raw.steps.flatMap((s: { actions?: unknown[] }) => s.actions ?? []);
    const heiferClick = actions.find(
      (a) => a.do === "click" && a.target?.within?.role === "group",
    );
    expect(heiferClick?.target?.within).toEqual({ role: "group", name: "Class" });
  });

  it("masks an email-shaped fill value and keeps a non-personal one as-is", () => {
    const { drafts } = convertPlaywrightFile(text, fixture);
    const raw = YAML.parse(drafts[0].yaml);
    const values = Object.values(raw.data as Record<string, string>);
    expect(values).toContain("person@example.com");
    expect(values).not.toContain("jordan@realcompany.com");
    expect(values).toContain("10");
  });

  it("counts the sign-in helper separately and notes it rather than treating it as a plain TODO", () => {
    const { drafts } = convertPlaywrightFile(text, fixture);
    expect(drafts[0].signInNotes).toBe(1);
    expect(drafts[0].yaml).toMatch(/sign-in: handled by the configured sign-in adapter/);
  });

  it("leaves unmapped calls (press, toBeChecked) as TODO comments and counts them", () => {
    const { drafts } = convertPlaywrightFile(text, fixture);
    const herd = drafts[0];
    expect(herd.unmapped).toBeGreaterThanOrEqual(2);
    expect(herd.yaml).toMatch(/TODO from test:.*press\('Enter'\)/);
    expect(herd.yaml).toMatch(/TODO from test:.*toBeChecked/);
  });

  it("carries a draft banner naming the source file and test title", () => {
    const { drafts } = convertPlaywrightFile(text, fixture);
    expect(drafts[0].yaml).toMatch(/^# DRAFT — generated by `docgen import playwright`/m);
    expect(drafts[0].yaml).toContain('test "ui: herd list search and filters (examples 10 to 12)"');
  });
});
