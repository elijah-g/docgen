// `docgen build`'s index stage: builds the help app's search-index.json + llms.txt, and (when
// `config.helpApp` is set) copies each walkthrough's generated page into the help app's content
// tree. See docs/scope.md "Swappable providers" (search: "an index file that ships with the
// help app; no database") and "Working with any agent".
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { buildSearchIndex } from "../index-search/index.js";
import type { BuildPageResult } from "../pages/index.js";
import { buildProcedures } from "../procedures/index.js";
import type { Procedure } from "../procedures/index.js";
import type { Walkthrough } from "../walkthrough/index.js";
import type { ResolvedChatConfig } from "../chat/index.js";

/** Reads a JSON array file if it exists and parses as an array; `undefined` if missing or
 * malformed (treated the same as "no prior procedures.json" rather than failing the build). */
function readJsonArrayIfExists<T>(file: string): T[] | undefined {
  if (!existsSync(file)) return undefined;
  try {
    const parsed = JSON.parse(readFileSync(file, "utf8"));
    return Array.isArray(parsed) ? (parsed as T[]) : undefined;
  } catch {
    return undefined;
  }
}

/** Header prepended (after any frontmatter) to every page mirrored into `content/docs/<id>` —
 * that tree is generated output, never a place to hand-edit (review finding index-stage.ts:20). */
function generatedHeader(id: string): string {
  // MDX-safe comment (not an HTML `<!-- -->` comment, which MDX's parser rejects — same fix
  // M6a already applied to the generated-block markers themselves; this header was missed).
  return `{/* Generated by docgen — edit in the Studio or pages/${id}/index.mdx */}\n\n`;
}

/** Marks a staged page file as generated by inserting `generatedHeader()` right after its
 * frontmatter block (or at the top, if it has none). No-op if already marked. */
function markGenerated(destFile: string, id: string): void {
  if (!existsSync(destFile)) return;
  const raw = readFileSync(destFile, "utf8");
  if (raw.includes("Generated by docgen")) return;
  const frontmatter = raw.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/);
  const header = generatedHeader(id);
  const content = frontmatter ? raw.slice(0, frontmatter[0].length) + header + raw.slice(frontmatter[0].length) : header + raw;
  writeFileSync(destFile, content, "utf8");
}

/**
 * `index-search/build.ts` walks every `.md`/`.mdx` file under its content dir as a page — it
 * doesn't know about pages' own `index.plain.md` (llms.txt source, not a second Fumadocs page;
 * see pages/build.ts). Stage only the real page file (+ non-markdown assets like screenshots)
 * into the content tree the search index is built from, so a page is never double-counted.
 *
 * `content/docs/<id>` is generated output, not a place a person edits (the source of truth is
 * `pages/<id>/index.mdx` — see `markGenerated` above). A non-publishable page is never staged —
 * and any stale copy from an earlier, passing build is removed — so a failed run can never leave
 * personal data, secrets, or a broken page visible in the sidebar/static params (review finding
 * index-stage.ts:68).
 */
function stagePageContent(pagesDir: string, contentDir: string, page: BuildPageResult): void {
  const dest = join(contentDir, page.id);
  if (!page.publishable) {
    rmSync(dest, { recursive: true, force: true });
    return;
  }
  const src = join(pagesDir, page.id);
  if (!existsSync(src)) return;
  rmSync(dest, { recursive: true, force: true });
  mkdirSync(dirname(dest), { recursive: true });
  const plainBasename = basename(page.plainFile);
  cpSync(src, dest, { recursive: true, filter: (candidate) => basename(candidate) !== plainBasename });
  markGenerated(join(dest, basename(page.indexFile)), page.id);
}

/** Removes `content/docs/<id>` directories whose walkthrough no longer exists on disk — so
 * deleting a walkthrough's `.yaml` file actually removes its page, instead of leaving an orphan
 * around forever (review finding index-stage.ts:20). */
function pruneDeletedWalkthroughs(contentDir: string, validIds: ReadonlySet<string>): void {
  if (!existsSync(contentDir)) return;
  for (const entry of readdirSync(contentDir, { withFileTypes: true })) {
    if (entry.isDirectory() && !validIds.has(entry.name)) {
      rmSync(join(contentDir, entry.name), { recursive: true, force: true });
    }
  }
}

/** Removes `<publicDir>/screenshots/<id>` for any id that's no longer publishable — either this
 * run attempted it (`attemptedIds`) but it didn't come out publishable, or it's for a walkthrough
 * deleted from disk (`validIds` given and it's missing). A page failing QA/not publishable this
 * run must never leave its screenshots live for `get_procedure`/MCP to keep serving (review
 * finding index-stage.ts:152). */
function pruneUnpublishedScreenshots(
  publicDir: string,
  attemptedIds: ReadonlySet<string>,
  publishableIds: ReadonlySet<string>,
  validIds?: ReadonlySet<string>,
): void {
  const screenshotsDir = join(publicDir, "screenshots");
  if (!existsSync(screenshotsDir)) return;
  for (const entry of readdirSync(screenshotsDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const id = entry.name;
    const deleted = validIds && !validIds.has(id);
    const unpublishable = attemptedIds.has(id) && !publishableIds.has(id);
    if (deleted || unpublishable) {
      rmSync(join(screenshotsDir, id), { recursive: true, force: true });
    }
  }
}

export interface IndexStageOptions {
  /** `<outDir>/pages` — every walkthrough's buildPage() output lives under `<pagesDir>/<id>/`. */
  pagesDir: string;
  /** Where to write search-index.json/llms.txt when `helpApp` isn't set. Usually `outDir`. */
  outDir: string;
  /** Absolute path to a Next.js help app (content/docs + public/), or undefined. */
  helpApp?: string;
  pages: BuildPageResult[];
  /** Every walkthrough id that currently exists on disk (not just the ones this run selected) —
   * used to prune `content/docs/<id>` for a walkthrough that's been deleted. Omit to skip
   * pruning (e.g. in tests that don't model the full walkthrough set). */
  walkthroughIds?: string[];
  /** `<outDir>/videos` (or helpApp's) — step video-time offsets in procedures.json come from
   * here when a render exists. Omit to skip (procedures.json just won't carry `videoTimeSec`). */
  videoDir?: string;
  /** One entry per `pages` result, carrying what the procedures builder needs that a
   * `BuildPageResult` doesn't (the walkthrough itself + its capture dir). Omit to skip
   * procedures.json entirely (e.g. tests that only care about search-index.json). */
  procedureSources?: { walkthrough: Walkthrough; captureDir: string }[];
  /** Resolved help-chat settings (`resolveChatConfig(config.chat, config.models)`), written to
   * `public/chat-config.json` so the help app's `/api/chat` route can read plain JSON off disk
   * at request time instead of importing the engine's config loader — `config/load.ts` reads
   * an arbitrary `docgen.config.ts` via a non-literal dynamic `import()` (through `tsx`), which
   * a route handler's bundler (Turbopack/webpack) can't statically trace. Never includes the
   * API key — that's always read from `process.env.ANTHROPIC_API_KEY` at request time, per
   * decisions.md #40 (owner's key only, never committed). Omit to skip writing the file (chat
   * then falls back to its own built-in defaults). */
  chatConfig?: ResolvedChatConfig;
}

export interface IndexStageResult {
  contentDir: string;
  searchIndexFile: string;
  llmsTxtFile: string;
  pageCount: number;
  /** True when pages were mirrored into a help app's content tree (config.helpApp was set). */
  copiedToHelpApp: boolean;
  /** Set when `procedureSources` was given — the procedures the MCP `get_procedure` tool and
   * chat's procedure-matching read from. */
  procedures?: Procedure[];
  proceduresFile?: string;
  /** Set when `chatConfig` was given. */
  chatConfigFile?: string;
}

/** Every id currently staged in `contentDir` — i.e. every published page on disk, not just the
 * ones this run rebuilt (review finding index-stage.ts:75: `docgen build foo` must not drop
 * every other walkthrough's llms.txt section). */
function publishedIds(contentDir: string): string[] {
  if (!existsSync(contentDir)) return [];
  return readdirSync(contentDir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

// `index.plain.md` is `stripMarkers(text)` of the full page (pages/build.ts) — markers stripped,
// but its leading YAML frontmatter block (`buildFrontmatterBlock`) is still there. That
// frontmatter is itself delimited by `---` lines, so it must be removed before a page's content
// goes into llms.txt, or it collides with the section delimiter below (review finding: get_page
// returned empty for every page because splitting on `\n---\n` cut pages apart at their own
// frontmatter's `---` lines, not just at section boundaries).
function stripFrontmatter(raw: string): string {
  const match = raw.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/);
  return match ? raw.slice(match[0].length) : raw;
}

// A line of bare `---` is valid inside page body Markdown (a horizontal rule) and is also what a
// page's own frontmatter uses, so it can't double as the section delimiter. This marker is never
// emitted by anything else that lands in llms.txt.
// Exported so `mcp/get-page.ts`'s parser splits on exactly the same delimiter this writes.
export const LLMS_TXT_SECTION_DELIMITER = "\n\n<!-- docgen:llms-txt-section -->\n\n";

function buildLlmsTxt(pagesDir: string, contentDir: string): string {
  const sections: string[] = [];
  for (const id of publishedIds(contentDir)) {
    const plainFile = join(pagesDir, id, "index.plain.md");
    if (!existsSync(plainFile)) continue;
    const content = stripFrontmatter(readFileSync(plainFile, "utf8")).trim();
    sections.push(`# ${id}\n\n${content}`);
  }
  return `${sections.join(LLMS_TXT_SECTION_DELIMITER)}\n`;
}

/**
 * Runs the index stage: optionally mirrors pages into a help app's content tree, then builds
 * search-index.json and llms.txt next to it (or under `outDir` when there's no help app).
 */
export function runIndexStage(opts: IndexStageOptions): IndexStageResult {
  const copiedToHelpApp = Boolean(opts.helpApp);
  // Always stage into a dedicated content dir, never index `pagesDir` directly — it also holds
  // each page's `index.plain.md` (llms.txt source), which would otherwise double-count as a
  // second page (see `stagePageContent`'s doc comment).
  const contentDir = opts.helpApp ? join(opts.helpApp, "content", "docs") : join(opts.outDir, ".search-content");
  const publicDir = opts.helpApp ? join(opts.helpApp, "public") : opts.outDir;

  for (const p of opts.pages) stagePageContent(opts.pagesDir, contentDir, p);

  if (opts.walkthroughIds) {
    pruneDeletedWalkthroughs(contentDir, new Set(opts.walkthroughIds));
  }

  mkdirSync(publicDir, { recursive: true });
  const searchIndexFile = join(publicDir, "search-index.json");
  const { pageCount } = buildSearchIndex(contentDir, searchIndexFile);

  const llmsTxtFile = join(publicDir, "llms.txt");
  writeFileSync(llmsTxtFile, buildLlmsTxt(opts.pagesDir, contentDir));

  let procedures: Procedure[] | undefined;
  let proceduresFile: string | undefined;
  if (opts.procedureSources) {
    // Only publishable pages get a procedure — same filter stagePageContent() applies, keyed by
    // id so a walkthrough whose page build failed never hands an agent steps (scope.md
    // "Truthfulness"; build-plan.md M15 step 1 "Only passed walkthroughs").
    const publishableIds = new Set(opts.pages.filter((p) => p.publishable).map((p) => p.id));
    const attemptedIds = new Set(opts.procedureSources.map((s) => s.walkthrough.walkthrough));
    const sources = opts.procedureSources
      .filter((s) => publishableIds.has(s.walkthrough.walkthrough))
      .map((s) => ({
        wf: s.walkthrough,
        captureDir: s.captureDir,
        lastChecked: opts.pages.find((p) => p.id === s.walkthrough.walkthrough)?.lastChecked,
      }));
    const proceduresFilePath = join(publicDir, "procedures.json");
    const existing = readJsonArrayIfExists<Procedure>(proceduresFilePath);
    const validIds = opts.walkthroughIds ? new Set(opts.walkthroughIds) : undefined;
    const result = buildProcedures({
      sources,
      videoDir: opts.videoDir,
      publicDir,
      existing,
      attemptedIds: [...attemptedIds],
      validIds: opts.walkthroughIds,
    });
    procedures = result.procedures;
    proceduresFile = result.outFile;
    pruneUnpublishedScreenshots(publicDir, attemptedIds, publishableIds, validIds);
  }

  let chatConfigFile: string | undefined;
  if (opts.chatConfig) {
    chatConfigFile = join(publicDir, "chat-config.json");
    writeFileSync(chatConfigFile, `${JSON.stringify(opts.chatConfig, null, 2)}\n`, "utf8");
  }

  return { contentDir, searchIndexFile, llmsTxtFile, pageCount, copiedToHelpApp, procedures, proceduresFile, chatConfigFile };
}
